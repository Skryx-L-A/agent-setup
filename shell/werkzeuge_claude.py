PLUGIN = "werkbank"
MCP_SERVERNAME = "werkbank"  # einziger Eintrag in der Plugin-.mcp.json
MARKTPLATZ = "~/.claude/werkbank-marktplatz"
MANIFEST = ".wb-werkzeuge-plugin.json"
SCHEMA_MANIFEST = "werkzeuge-plugin/1"
HUB_PORT = 8790
KOPF = "generated by wb-werkzeuge, nicht von Hand aendern"
ERZEUGT_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]*$")
# So heisst ein Hub-Werkzeug in Claude: mcp__plugin_<plugin>_<server>__<server>-<tool>
HUB_PRAEFIX = "mcp__plugin_%s_%s__" % (PLUGIN, MCP_SERVERNAME)


# ---------------------------------------------------------------- Weiche (Haken zustaendig/main)

def zustaendig(argv):
    """Nur Aufrufe, die ausdruecklich --plugin oder --settings nennen, gehen hierher; alles
    andere bleibt beim Kern (damit `apply claude` ohne Flag settings.json nie beruehrt)."""
    return (len(argv) >= 4 and argv[1] in ("plan", "apply") and "claude" in argv[2:]
            and ("--plugin" in argv or "--settings" in argv))


# ---------------------------------------------------------------- Quelle -> Soll-Dateien

def _sha_text(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _json_text(daten):
    return json.dumps(daten, indent=2, ensure_ascii=False) + "\n"


def _fuer_claude(q, reg, art):
    """[(name, eintrag)] der Quelle, die fuer Harness claude auf dieser Maschine gelten."""
    m = kern.maschine()
    out = []
    for name, e in (q.get(art) or {}).items():
        if m not in e.get("maschinen", [m]) or e.get("status"):
            continue
        if "claude" in kern.harnesses_aufloesen(e.get("harnesses", []), art, reg):
            out.append((name, e))
    return out


def hub_url(q):
    port = ((q.get("hub") or {}).get("port")) or HUB_PORT
    return "http://127.0.0.1:%d/mcp?harness=claude" % int(port)


def mcp_json(q, reg=None):
    """Plugin-.mcp.json: der Hub-Eintrag werkbank, dazu direkt die Eintraege mit ueber_hub false
    (entfernte Server mit OAuth im Client, die der Hub nicht bedienen kann)."""
    server = {MCP_SERVERNAME: {
        "type": "http", "url": hub_url(q), "headersHelper": "wb-hub token-header"}}
    if reg is not None:
        for name, e in _fuer_claude(q, reg, "mcp"):
            if kern.ohne_hub(e) and name not in server:
                server[name] = {"type": "http", "url": e["url"]}
    return {"mcpServers": server}


def ereignis_teilen(s):
    """'PreToolUse:Write|Edit' -> ('PreToolUse', 'Write|Edit'); 'Stop' -> ('Stop', None)."""
    ereignis, _, matcher = s.partition(":")
    return ereignis, (matcher or None)


def hooks_json(q, reg):
    """hooks/hooks.json: je Ereignis Gruppen je Matcher (Reihenfolge der Quelle)."""
    gruppen = {}
    for _name, e in _fuer_claude(q, reg, "hooks"):
        eintrag = {"type": "command", "command": e["befehl"]}
        if e.get("timeout") is not None:
            eintrag["timeout"] = e["timeout"]
        for s in e["ereignisse"]:
            ereignis, matcher = ereignis_teilen(s)
            liste = gruppen.setdefault(ereignis, [])
            g = next((x for x in liste if x.get("matcher") == matcher), None)
            if g is None:
                g = {"hooks": []}
                if matcher is not None:
                    g = {"matcher": matcher, "hooks": []}
                liste.append(g)
            g["hooks"].append(dict(eintrag))
    return {"description": KOPF, "hooks": gruppen}


def prompt_dateien(q, reg):
    """-> ({relpfad: text}, [Fehlertext]). Der Dateiname kommt aus dem Quellschluessel und
    wird deshalb auf [A-Za-z0-9_-] geprueft (kein Pfadausbruch)."""
    out, fehler = {}, []
    for name, e in _fuer_claude(q, reg, "prompts"):
        if not ERZEUGT_NAME.match(name):
            fehler.append("PROMPT-NAME-UNGUELTIG prompts.%s: nur Buchstaben, Ziffern, _ und -" % name)
            continue
        datei = kern.pfad_aufloesen(e.get("datei", ""))
        try:
            with open(datei, encoding="utf-8", newline="") as f:
                out["%s/commands/%s.md" % (PLUGIN, name)] = f.read()
        except (OSError, UnicodeDecodeError):
            fehler.append("PROMPT-DATEI-FEHLT prompts.%s: %s" % (name, e.get("datei")))
    return out, fehler


def soll_dateien(q, reg):
    """-> ({relpfad: text}, [Fehlertext]); relpfad ist relativ zur Marktplatzwurzel."""
    inhalt = {
        "%s/.mcp.json" % PLUGIN: _json_text(mcp_json(q, reg)),
        "%s/hooks/hooks.json" % PLUGIN: _json_text(hooks_json(q, reg)),
    }
    prompts, fehler = prompt_dateien(q, reg)
    inhalt.update(prompts)
    # Die Version folgt dem Inhalt: Claude haelt Plugins nach Version im Cache, eine
    # unveraenderte Nummer wuerde neue Hooks oder Befehle nie nachladen.
    h = hashlib.sha256()
    for k in sorted(inhalt):
        h.update(k.encode() + b"\0" + inhalt[k].encode("utf-8") + b"\0")
    version = "0.1.%d" % (int(h.hexdigest()[:7], 16))
    inhalt["%s/.claude-plugin/plugin.json" % PLUGIN] = _json_text({
        "name": PLUGIN, "version": version,
        "description": "Werkbank: Hooks, Befehle und der Hub-Zugang (%s)" % KOPF,
        "author": {"name": "Werkbank"}})
    inhalt[".claude-plugin/marketplace.json"] = _json_text({
        "name": PLUGIN, "owner": {"name": "Werkbank"},
        "description": "Lokaler Werkbank-Marktplatz (%s)" % KOPF,
        "plugins": [{"name": PLUGIN, "source": "./%s" % PLUGIN,
                     "description": "Werkbank-Plugin (%s)" % KOPF}]})
    return inhalt, fehler


# ---------------------------------------------------------------- Besitz und Schreiben

def _manifest_laden(wurzel):
    p = os.path.join(wurzel, MANIFEST)
    if not os.path.exists(p):
        return {}
    try:
        with open(p, encoding="utf-8") as f:
            m = json.load(f)
        d = m["dateien"]
        if not isinstance(d, dict):
            raise ValueError
        return d
    except (OSError, ValueError, KeyError):
        # Ohne gueltiges Manifest gilt nichts als eigen; bestehende Dateien bleiben stehen.
        return None


def _lesen(p):
    try:
        with open(p, encoding="utf-8", newline="") as f:
            return f.read()
    except (OSError, UnicodeDecodeError):
        return None


def bewerten(q, reg, wurzel):
    """-> (aktionen, fehler). aktion = (zustand, relpfad, text|None). Zustaende: NEU, GLEICH,
    VERALTET (schreiben), ABGEWICHEN, FREMD (stehen lassen), ENTFERNEN, ABGEWICHEN-ALT."""
    soll, fehler = soll_dateien(q, reg)
    man = _manifest_laden(wurzel)
    if man is None:
        fehler.append("MANIFEST-UNLESBAR %s: nichts gilt als eigen, bestehende Dateien bleiben" % MANIFEST)
        man = {}
    aktionen = []
    for rel in sorted(soll):
        p = os.path.join(wurzel, rel)
        text = soll[rel]
        if not os.path.lexists(p):
            aktionen.append(("NEU", rel, text))
            continue
        ist = _lesen(p)
        if ist is not None and _sha_text(ist) == _sha_text(text):
            aktionen.append(("GLEICH", rel, text))
        elif ist is not None and rel in man and man[rel] == _sha_text(ist):
            aktionen.append(("VERALTET", rel, text))
        elif rel in man:
            aktionen.append(("ABGEWICHEN", rel, text))
        else:
            aktionen.append(("FREMD", rel, text))
    for rel in sorted(set(man) - set(soll)):
        p = os.path.join(wurzel, rel)
        if not os.path.lexists(p):
            continue
        ist = _lesen(p)
        if ist is not None and man[rel] == _sha_text(ist):
            aktionen.append(("ENTFERNEN", rel, None))
        else:
            aktionen.append(("ABGEWICHEN-ALT", rel, None))
    return aktionen, fehler


def _leere_ordner_entfernen(wurzel, rel):
    d = os.path.dirname(os.path.join(wurzel, rel))
    while d.startswith(wurzel + os.sep):
        try:
            os.rmdir(d)  # nur wenn leer
        except OSError:
            break
        d = os.path.dirname(d)


def erzeugen(q, reg, wurzel, nur_plan=False):
    """-> (zeilen, rc). rc 0 sauber, 1 mit Befund (FREMD/ABGEWICHEN/Fehler). Mit nur_plan wird
    nichts geschrieben."""
    aktionen, fehler = bewerten(q, reg, wurzel)
    zeilen, rc = [], 0
    for f in fehler:
        zeilen.append("FEHLER  %s" % f)
        rc = 1
    schreib = [a for a in aktionen if a[0] in ("NEU", "VERALTET", "ENTFERNEN")]
    man = _manifest_laden(wurzel) or {}
    snaps = kern.Snapshots()
    for zustand, rel, text in aktionen:
        p = os.path.join(wurzel, rel)
        if zustand == "GLEICH":
            continue
        if zustand in ("ABGEWICHEN", "ABGEWICHEN-ALT", "FREMD"):
            warum = {"ABGEWICHEN": "von Hand geaendert", "ABGEWICHEN-ALT": "von Hand geaendert, nicht mehr in der Quelle",
                     "FREMD": "nicht von der Werkbank erzeugt"}[zustand]
            zeilen.append("%-10s %s: bleibt stehen (%s)" % (zustand, rel, warum))
            rc = 1
            continue
        verb = {"NEU": "ANLEGEN", "VERALTET": "AKTUALISIEREN", "ENTFERNEN": "ENTFERNEN"}[zustand]
        if nur_plan:
            zeilen.append("%-13s %s" % (verb, rel))
            continue
        if zustand == "ENTFERNEN":
            snap = snaps.sichern("claude", p)
            os.unlink(p)
            _leere_ordner_entfernen(wurzel, rel)
            man.pop(rel, None)
            zeilen.append("ENTFERNT       %s (Snapshot %s)" % (rel, snap))
            continue
        snap = snaps.sichern("claude", p) if zustand == "VERALTET" else None
        os.makedirs(os.path.dirname(p), exist_ok=True)
        atomar_schreiben.schreiben(p, text, modus=0o644, newline="")
        man[rel] = _sha_text(text)
        zeilen.append("GESCHRIEBEN    %s%s" % (rel, " (Snapshot %s)" % snap if snap else ""))
    if not nur_plan and schreib:
        os.makedirs(wurzel, exist_ok=True)
        mtext = _json_text({"schema": SCHEMA_MANIFEST, "dateien": dict(sorted(man.items()))})
        mp = os.path.join(wurzel, MANIFEST)
        snaps.sichern("claude", mp)
        atomar_schreiben.schreiben(mp, mtext, modus=0o644, newline="")
    if not zeilen:
        zeilen.append("nichts zu schreiben")
    return zeilen, rc


# ---------------------------------------------------------------- settings.json: Plan

def server_namen(q):
    return sorted(q.get("mcp") or {})


def _namens_muster(q):
    s = "|".join(re.escape(n) for n in server_namen(q))
    if not s:
        return None, None
    # mcp__<server>__<tool> und mcp__plugin_<server>_<server>__<tool>
    voll = re.compile(r"mcp__(?:plugin_(?P<p>%s)_(?P=p)|(?P<d>%s))__(?P<t>[A-Za-z0-9_]+)" % (s, s))
    blank = re.compile(r"mcp__(?:plugin_(?P<p>%s)_(?P=p)|(?P<d>%s))(?![A-Za-z0-9_])(?!__)" % (s, s))
    return voll, blank


def umbenennen(text, q):
    """mcp__brain__search -> mcp__plugin_werkbank_werkbank__brain-search (auch in Matchern).
    -> (neuer_text, [blanke Servernamen ohne Werkzeug, nur melden])."""
    voll, blank = _namens_muster(q)
    if voll is None:
        return text, []

    def ersetze(m):
        server = m.group("p") or m.group("d")
        return "%s%s-%s" % (HUB_PRAEFIX, server, m.group("t"))
    neu = voll.sub(ersetze, text)
    return neu, [m.group(0) for m in blank.finditer(text)]


def _matcher_norm(m):
    return "*" if m in (None, "", "*") else m


def hook_triple(q, reg):
    """{(ereignis, matcher-normalisiert, befehl)} -- was das Plugin traegt."""
    s = set()
    for _n, e in _fuer_claude(q, reg, "hooks"):
        for ev in e["ereignisse"]:
            ereignis, matcher = ereignis_teilen(ev)
            s.add((ereignis, _matcher_norm(matcher), e["befehl"]))
    return s


def _ist_doppelt(ereignis, gruppe, h, triple):
    return h.get("type", "command") == "command" and (ereignis, _matcher_norm(gruppe.get("matcher")),
                                                        h.get("command")) in triple


def settings_plan(q, reg, alt):
    """alt = geparstes settings.json-Objekt. -> (neu, aenderungen[], hinweise[]). Aendert alt nicht."""
    neu = json.loads(json.dumps(alt))
    aend, hinweise = [], []
    wurzel = kern.pfad_aufloesen(MARKTPLATZ)

    mk = neu.setdefault("extraKnownMarketplaces", {})
    soll_mk = {"source": {"source": "directory", "path": wurzel}}
    if mk.get(PLUGIN) != soll_mk:
        aend.append("%s extraKnownMarketplaces.%s = directory %s" % ("~" if PLUGIN in mk else "+", PLUGIN, wurzel))
        mk[PLUGIN] = soll_mk
    ep = neu.setdefault("enabledPlugins", {})
    schluessel = "%s@%s" % (PLUGIN, PLUGIN)
    if ep.get(schluessel) is not True:
        aend.append("%s enabledPlugins[%s] = true" % ("~" if schluessel in ep else "+", schluessel))
        ep[schluessel] = True

    # Direkte Werkbank-Hooks, die das Plugin traegt, entfallen (sonst feuern sie doppelt).
    triple = hook_triple(q, reg)
    befehle = {t[2] for t in triple}
    hooks = neu.get("hooks")
    if isinstance(hooks, dict):
        for ereignis in list(hooks):
            gruppen = hooks[ereignis]
            if not isinstance(gruppen, list):
                continue
            behalten = []
            for g in gruppen:
                if not isinstance(g, dict) or not isinstance(g.get("hooks"), list):
                    behalten.append(g)
                    continue
                rest = []
                for h in g["hooks"]:
                    if isinstance(h, dict) and _ist_doppelt(ereignis, g, h, triple):
                        aend.append("- hooks.%s[matcher=%s]: %s (kommt aus dem Plugin)"
                                    % (ereignis, g.get("matcher", "<keiner>"), h.get("command")))
                    else:
                        if isinstance(h, dict) and h.get("command") in befehle:
                            hinweise.append("HINWEIS hooks.%s[matcher=%s]: %s steht auch im Plugin, aber unter "
                                            "anderem Ereignis oder Matcher; bleibt stehen, Doppelfeuern pruefen"
                                            % (ereignis, g.get("matcher", "<keiner>"), h.get("command")))
                        rest.append(h)
                if rest:
                    behalten.append(dict(g, hooks=rest))
                elif not g["hooks"]:
                    behalten.append(g)
            if behalten:
                hooks[ereignis] = behalten
            else:
                del hooks[ereignis]
        if not hooks:
            del neu["hooks"]

    # mcp__<server>__<tool> -> Hub-Namen in Rechten und in Matchern der uebrigen Hooks.
    perms = neu.get("permissions")
    if isinstance(perms, dict):
        for liste_name in ("allow", "deny", "ask"):
            liste = perms.get(liste_name)
            if not isinstance(liste, list):
                continue
            for i, eintrag in enumerate(liste):
                if not isinstance(eintrag, str):
                    continue
                n, blank = umbenennen(eintrag, q)
                if n != eintrag:
                    aend.append("~ permissions.%s: %s -> %s" % (liste_name, eintrag, n))
                    liste[i] = n
                for b in blank:
                    hinweise.append("HINWEIS permissions.%s: %s nennt den ganzen Server; der Hub kennt nur "
                                    "%s<server>-<werkzeug>, von Hand aufteilen" % (liste_name, eintrag, HUB_PRAEFIX))
    if isinstance(neu.get("hooks"), dict):
        for ereignis, gruppen in neu["hooks"].items():
            for g in gruppen if isinstance(gruppen, list) else []:
                if isinstance(g, dict) and isinstance(g.get("matcher"), str):
                    n, blank = umbenennen(g["matcher"], q)
                    if n != g["matcher"]:
                        aend.append("~ hooks.%s matcher: %s -> %s" % (ereignis, g["matcher"], n))
                        g["matcher"] = n
                    for b in blank:
                        hinweise.append("HINWEIS hooks.%s matcher %s nennt den ganzen Server; von Hand aufteilen"
                                        % (ereignis, g["matcher"]))
    return neu, aend, hinweise


def _settings_lesen(pfad):
    """-> (text|None, daten). Fehlt die Datei: (None, {}). Ungueltig: ValueError."""
    if not os.path.exists(pfad):
        return None, {}
    with open(pfad, encoding="utf-8", newline="") as f:
        text = f.read()
    daten = json.loads(text) if text.strip() else {}
    if not isinstance(daten, dict):
        raise ValueError("Wurzel ist kein Objekt")
    return text, daten


GEHEIM_SCHLUESSEL = re.compile(r"(token|secret|passw|api[_-]?key|credential|auth)", re.I)
VERDECKT = "<verdeckt>"


def verdecken(daten, pfad=""):
    """Kopie fuer die Ausgabe: Werte unter env und unter geheimnisverdaechtigen Schluesseln werden
    durch <verdeckt> ersetzt (settings.json kann Zugangsdaten in env tragen). Pruefsummen und Plan
    rechnen weiter mit dem echten Inhalt."""
    if isinstance(daten, dict):
        aus = {}
        for k, v in daten.items():
            if (pfad == "" and k == "env" and isinstance(v, dict)):
                aus[k] = {ek: VERDECKT for ek in v}
            elif isinstance(v, (str, int, float)) and not isinstance(v, bool) and GEHEIM_SCHLUESSEL.search(str(k)):
                aus[k] = VERDECKT
            else:
                aus[k] = verdecken(v, pfad + "." + str(k))
        return aus
    if isinstance(daten, list):
        return [verdecken(v, pfad) for v in daten]
    return daten


def settings_plan_ausgeben(q, reg, als_json):
    """Liest settings.json unter $HOME, schreibt nichts. -> rc. Die Ausgabe (Diff und `neu` in
    --json) zeigt Werte unter env und geheimnisverdaechtigen Schluesseln nur verdeckt; BASIS-SHA und
    PLAN-SHA gelten fuer den echten Inhalt. Wer den Plan anwendet, rechnet ihn mit settings_plan neu
    und vergleicht PLAN-SHA, statt `neu` aus der Ausgabe zu schreiben."""
    pfad = os.path.join(kern.home(), ".claude", "settings.json")
    try:
        text, alt = _settings_lesen(pfad)
    except (OSError, ValueError, UnicodeDecodeError) as e:
        print("ZIEL-UNLESBAR %s: %s (nichts geplant)" % (pfad, type(e).__name__), file=sys.stderr)
        return 2
    neu, aend, hinweise = settings_plan(q, reg, alt)
    neu_text = kern.json_serialisieren(neu, text)
    basis_sha = _sha_text(text or "")
    plan_sha = _sha_text(neu_text)
    if als_json:
        print(json.dumps({"schema": "werkzeuge-settings-plan/1", "datei": pfad, "basis_sha": basis_sha,
                          "plan_sha": plan_sha, "aenderungen": aend, "hinweise": hinweise,
                          "neu": verdecken(neu), "verdeckt": VERDECKT},
                         ensure_ascii=False))
        return 0
    print("wb-werkzeuge plan claude --settings (schreibt nichts)")
    print("Datei:     %s%s" % (pfad, "" if text is not None else " (fehlt, Plan gegen leeres Objekt)"))
    print("BASIS-SHA: %s" % basis_sha)
    print("PLAN-SHA:  %s" % plan_sha)
    if not aend and not hinweise:
        print("keine Aenderung noetig")
        return 0
    for z in aend + hinweise:
        print(z)
    if text is not None and kern.json_serialisieren(alt, text) != text:
        print("HINWEIS Format: die Datei wird beim Anwenden neu formatiert (der Diff zeigt nur Inhalte)")
    diff = list(difflib.unified_diff(kern.json_serialisieren(verdecken(alt), text).splitlines(),
                                     kern.json_serialisieren(verdecken(neu), text).splitlines(),
                                     "settings.json (jetzt)", "settings.json (Plan)", lineterm="", n=2))
    if diff:
        print("--- Diff ---")
        print("\n".join(diff))
    return 0


def _settings_snapshot(pfad):
    """Kopie von settings.json unter ~/.local/trash-snapshots/<datum>-settings/ -> Pfad oder None."""
    if not os.path.exists(pfad):
        return None
    jetzt = datetime.datetime.now()
    verz = os.path.join(kern.home(), ".local", "trash-snapshots", jetzt.strftime("%Y-%m-%d") + "-settings")
    os.makedirs(verz, exist_ok=True)
    basis = "settings.json.%s" % jetzt.strftime("%H%M%S")
    ziel, n = os.path.join(verz, basis), 1
    while os.path.exists(ziel):
        ziel = os.path.join(verz, "%s.%d" % (basis, n))
        n += 1
    shutil.copy2(pfad, ziel)
    return ziel


def _settings_zurueck(pfad, snap):
    """Stellt den Stand vor apply wieder her, unabhaengig von atomar_schreiben (das eben versagt
    haben kann): Kopie neben das Ziel, dann os.replace. Ohne Snapshot gab es die Datei vorher nicht."""
    if snap is None:
        if os.path.lexists(pfad):
            os.unlink(pfad)
        return
    tmp = pfad + ".wb-zurueck"
    shutil.copy2(snap, tmp)
    os.replace(tmp, pfad)


def settings_anwenden(q, reg, plan_sha_soll, basis_sha_soll=None):
    """apply claude --settings: schreibt den neu berechneten Plan nur, wenn er dem gelesenen
    entspricht. -> rc 0 geschrieben oder nichts zu tun, 1 Gegenprobe misslungen (zurueckgerollt),
    2 abgewiesen (nichts geschrieben). Gibt keine Werte aus, nur Pruefsummen und die Aenderungszeilen
    wie plan."""
    pfad = os.path.join(kern.home(), ".claude", "settings.json")
    try:
        text, alt = _settings_lesen(pfad)
    except (OSError, ValueError, UnicodeDecodeError) as e:
        print("ZIEL-UNLESBAR %s: %s (nichts geschrieben)" % (pfad, type(e).__name__), file=sys.stderr)
        return 2
    neu, aend, _hinweise = settings_plan(q, reg, alt)
    neu_text = kern.json_serialisieren(neu, text)
    basis_sha = _sha_text(text or "")
    plan_sha = _sha_text(neu_text)
    if basis_sha_soll is not None and basis_sha_soll != basis_sha:
        print("BASIS-SHA passt nicht: erwartet %s, jetzt %s; settings.json hat sich seit dem Plan geaendert "
              "(nichts geschrieben, Plan neu lesen)" % (basis_sha_soll, basis_sha), file=sys.stderr)
        return 2
    if plan_sha_soll != plan_sha:
        print("PLAN-SHA passt nicht: erwartet %s, jetzt %s (nichts geschrieben, Plan neu lesen)"
              % (plan_sha_soll, plan_sha), file=sys.stderr)
        return 2
    print("wb-werkzeuge apply claude --settings")
    print("Datei:     %s" % pfad)
    print("BASIS-SHA: %s" % basis_sha)
    print("PLAN-SHA:  %s" % plan_sha)
    if text is not None and neu_text == text:
        print("nichts zu tun")
        return 0
    snap = _settings_snapshot(pfad)
    if snap:
        print("SNAPSHOT   %s" % snap)
    try:
        modus = (os.stat(pfad).st_mode & 0o777) if text is not None else 0o644
        atomar_schreiben.schreiben(pfad, neu_text, modus=modus, newline="")
    except OSError as e:
        _settings_zurueck(pfad, snap)
        print("SCHREIBEN MISSLUNGEN (%s), Stand vor apply wiederhergestellt" % type(e).__name__, file=sys.stderr)
        return 1
    # Gegenprobe: neu lesen, gueltiges JSON, Inhalt wie geplant, erneuter Plan ohne Aenderung.
    try:
        text2, alt2 = _settings_lesen(pfad)
        _neu2, aend2, _ = settings_plan(q, reg, alt2)
        gut = text2 == neu_text and not aend2
        grund = "Inhalt weicht vom Plan ab" if text2 != neu_text else "erneuter Plan nicht leer"
    except (OSError, ValueError, UnicodeDecodeError) as e:
        gut, grund = False, "nicht lesbar (%s)" % type(e).__name__
    if not gut:
        _settings_zurueck(pfad, snap)
        print("GEGENPROBE MISSLUNGEN: %s; Stand vor apply wiederhergestellt%s"
              % (grund, " aus %s" % snap if snap else " (Datei entfernt)"), file=sys.stderr)
        return 1
    for z in aend:
        print(z)
    print("GESCHRIEBEN %s (Gegenprobe: gueltiges JSON, erneuter Plan ohne Aenderung)" % pfad)
    return 0


# ---------------------------------------------------------------- CLI

def main(argv):
    befehl = argv[1]
    json_aus = "--json" in argv
    ziel = None
    if "--ziel" in argv:
        i = argv.index("--ziel")
        if i + 1 >= len(argv):
            print("wb-werkzeuge: --ziel braucht ein Verzeichnis", file=sys.stderr)
            return 2
        ziel = argv[i + 1]
    try:
        q, reg = kern.laden()
    except kern.FehlerInQuelle as ex:
        for f in ex.fehler:
            print("FEHLER %s %s: %s" % (f["code"], f["eintrag"], f["text"]), file=sys.stderr)
        return 2
    if "--settings" in argv:
        if befehl != "plan":
            werte = {}
            for flag in ("--plan-sha", "--basis-sha"):
                if flag in argv:
                    i = argv.index(flag)
                    werte[flag] = argv[i + 1] if i + 1 < len(argv) else ""
                    if not re.match(r"^[0-9a-f]{64}$", werte[flag]):
                        print("wb-werkzeuge: %s braucht eine SHA-256 (64 Hexzeichen)" % flag, file=sys.stderr)
                        return 2
            if "--plan-sha" not in werte:
                print("wb-werkzeuge: apply claude --settings braucht --plan-sha <PLAN-SHA> aus "
                      "`wb-werkzeuge plan claude --settings` (nichts geschrieben)", file=sys.stderr)
                return 2
            return settings_anwenden(q, reg, werte["--plan-sha"], werte.get("--basis-sha"))
        return settings_plan_ausgeben(q, reg, json_aus)
    wurzel = kern.pfad_aufloesen(ziel or MARKTPLATZ)
    zeilen, rc = erzeugen(q, reg, wurzel, nur_plan=(befehl == "plan"))
    print("\n".join(zeilen))
    return rc


# ---------------------------------------------------------------- status (Haken bewerten)

ZUSTAND_AUS_PLUGIN = {"NEU": "FEHLT", "GLEICH": "GLEICH", "VERALTET": "VERALTET",
                      "ABGEWICHEN": "ABGEWICHEN", "FREMD": "ABGEWICHEN"}


def _bewerten(roh, q, reg, state, nur_harness=None, nur_art=None):
    """Haken `bewerten`: der Hub-Eintrag werkbank erreicht Claude ueber die Plugin-.mcp.json
    (headersHelper `wb-hub token-header`), nicht ueber ~/.claude.json (E4). Der Kern meldet ihn OFFEN;
    hier wird er durch den Zustand der Plugin-Datei ersetzt. Der Kern schreibt ihn weiter nicht
    (apply sieht nur seine eigenen Eintraege); geschrieben wird er mit `apply claude --plugin`."""
    aus = []
    for x in roh:
        e = (q.get("mcp") or {}).get(x["name"])
        if (x["harness"] == "claude" and x["art"] == "mcp" and x["zustand"] == "OFFEN"
                and (kern.ist_hub_eintrag(e) or kern.ohne_hub(e)) and not (e or {}).get("status")):
            wurzel = kern.pfad_aufloesen(MARKTPLATZ)
            rel = "%s/.mcp.json" % PLUGIN
            aktionen, _ = bewerten(q, reg, wurzel)
            z = next((a[0] for a in aktionen if a[1] == rel), "NEU")
            grund = {"NEU": "Plugin-.mcp.json fehlt: wb-werkzeuge apply claude --plugin",
                     "VERALTET": "Plugin-.mcp.json veraltet: wb-werkzeuge apply claude --plugin",
                     "ABGEWICHEN": "Plugin-.mcp.json von Hand geaendert (bleibt stehen)",
                     "FREMD": "Plugin-.mcp.json nicht von der Werkbank erzeugt (bleibt stehen)"}.get(z)
            x = dict(x, zustand=ZUSTAND_AUS_PLUGIN.get(z, "OFFEN"), grund=grund,
                     ziel="%s/%s" % (MARKTPLATZ, rel))
            for k in ("wert", "pfad", "datei"):
                x.pop(k, None)
        aus.append(x)
    return aus


def registrieren():
    """Traegt den Claude-Adapter in den Kern ein (idempotent): --plugin und --settings gehoeren ihm,
    dazu der Status des Hub-Eintrags ueber das Plugin."""
    kern.adapter_registrieren("claude", zustaendig=zustaendig, main=main, bewerten=_bewerten)

"""werkzeuge_claude -- Claude-Adapter von `wb-werkzeuge`: das Werkbank-Plugin und der Diff fuer
settings.json.

Plan: ~/AI/_recherche/werkzeug-plan-2026-10-13.md (2.1, 3.4), Hub-Entwurf 5.1 (S2).

Zwei Befehle, beide von `wb-werkzeuge` nur durchgereicht (siehe `zustaendig`):

  wb-werkzeuge plan  claude --plugin [--ziel <dir>]   zeigt, was apply im Plugin schreiben wuerde
  wb-werkzeuge apply claude --plugin [--ziel <dir>]   erzeugt/aktualisiert Marktplatz und Plugin
  wb-werkzeuge plan  claude --settings [--json]       Diff fuer ~/.claude/settings.json, schreibt NICHTS
  wb-werkzeuge apply claude --settings --plan-sha <PLAN-SHA> [--basis-sha <BASIS-SHA>]
                                                      schreibt genau den gelesenen Plan (E4)

`apply claude --settings` ohne --plan-sha wird abgewiesen (Exit 2): geschrieben wird nur ein Plan,
den jemand vorher mit `plan claude --settings` gelesen hat. apply rechnet den Plan neu und bricht
ohne Schreiben ab (Exit 2), wenn PLAN-SHA oder BASIS-SHA nicht passen; sonst Snapshot unter
~/.local/trash-snapshots/<datum>-settings/, atomar schreiben, neu lesen und gegenpruefen (gueltiges
JSON, erneuter Plan ohne Aenderung); misslingt das, wird der Snapshot zurueckgespielt (Exit 1).

Das Plugin `werkbank` (Marktplatz ~/.claude/werkbank-marktplatz/) enthaelt:
  .claude-plugin/plugin.json      Name, Version (aus dem Inhalt abgeleitet)
  .mcp.json                       NUR den Server `werkbank` (HTTP zum Hub plus headersHelper)
  hooks/hooks.json                aus dem Abschnitt `hooks` der Quelle, nur fuer Harness claude
  commands/<name>.md              aus den Prompts der Quelle
Besitz: Eine Manifestdatei am Marktplatzwurzel haelt die Pruefsumme jeder erzeugten Datei.
Nur was dort steht, wird ueberschrieben oder entfernt, und nur solange es unveraendert ist.
Fremde und von Hand geaenderte Dateien bleiben stehen und werden gemeldet. Vor jedem
Ueberschreiben oder Entfernen legt `werkzeuge_kern.Snapshots` eine Sicherung an.
"""
import datetime
import difflib
import hashlib
import json
import os
import re
import shutil

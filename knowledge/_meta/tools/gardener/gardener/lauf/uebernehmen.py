def uebernehmen(buch: Buch, writer: VaultWriter, *, listen: Iterable[Path] = LISTEN_STANDARD,
                zellen_datei: Path | None = ZELLEN_STANDARD, einbetten=None, gleich_cos: float = 0.62,
                kern_max: int = KERN_MAX, kern_top: int = KERN_TOP, lauf_id: str = "uebernahme",
                heute: str | None = None, ids: Iterable[str] | None = None,
                freigabe: str | None = None) -> UebernahmeErgebnis:
    """``ids`` (with ``freigabe``, e.g. ``ok orchestrator %32``): take over exactly these
    packages; ``listen``/``zellen_datei`` are then ignored.  Without ``ids`` the list and
    cell selection applies (the ready list of ``lauf.uebernehmen``, written only dry)."""
    vault = writer.vault
    datum = heute or dt.date.today().isoformat()
    ergebnis = UebernahmeErgebnis(dry_run=writer.dry_run)
    loader = schreiben_mod._tripwire_loader()
    if ids is not None:
        if not freigabe:
            raise ValueError("ids ohne freigabe")
        kand = kandidaten_ids(buch, vault, ids, freigabe, ergebnis)
    else:
        kand = kandidaten(buch, vault, listen, belegte_zellen(zellen_datei), ergebnis)
    vorhanden = {p: vorhandene_aussagen(vault, p, loader) for p in {k.row["projekt"] for k in kand}}
    behalten, duplikate = zusammenfuehren(kand, einbetten=einbetten, gleich_cos=gleich_cos,
                                          vorhanden=vorhanden)
    for k, mit in duplikate:
        ergebnis.duplikate += 1
        buch.paket_update(k.row["paket_id"], status="duplikat", abgleich=[
            {"mit": mit, "urteil": "gleich", "status": "uebernahme", "konfidenz": 1.0}])
    ergebnis.vorschlaege = [vorschlag(buch, k) for k in behalten]
    je_projekt: dict[str, list[Kandidat]] = {}
    for k in behalten:
        je_projekt.setdefault(k.row["projekt"], []).append(k)

    for projekt, ks in sorted(je_projekt.items()):
        base = f"20-projects/{projekt}"
        fallen_k = [k for k in ks if _ziel_fallen(k.row)]
        ent_k = [k for k in ks if not _ziel_fallen(k.row)]
        ok_fallen = ok_ent = True
        # the whole own section is regenerated from the book: earlier take-overs stay
        frueher = buch.conn.execute(
            "SELECT * FROM lauf_pakete WHERE projekt=? AND status='uebernommen' AND ziel=? "
            "ORDER BY created, paket_id", (projekt, "FALLEN.yaml#uebernommen")).fetchall()
        if fallen_k:
            rel = f"{base}/FALLEN.yaml"
            path = vault / rel
            old = read_text(path) if path.exists() else None
            eintraege = [(r, _herkunft(r), _uebernahme_datum(r, datum)) for r in frueher] + \
                [(k.row, k.herkunft, datum) for k in fallen_k]
            ids = {r["paket_id"][:10] for r, _h, _d in eintraege}
            abgleich, why = abgleich_fallen(old, eintraege, {k.row["paket_id"] for k in fallen_k})
            new, why = (fallen_mit_uebernahme(old, projekt, abgleich.abschnitt, ids)
                        if abgleich is not None else (None, why))
            problem = why if new is None else pruefe_fallen(old, new, loader, ids, abgleich.status)
            if problem:
                ergebnis.verweigert.append((rel, problem))
                ok_fallen = False
            else:
                ok_fallen = writer.write(path, new, expect=old)
                if not ok_fallen:
                    ergebnis.verweigert.append((rel, "schreibtor"))
                else:
                    _buche_fallen_abgleich(buch, abgleich, rel, datum, lauf_id, ergebnis)
                    ergebnis.zaehle(rel, "fallen", len(fallen_k))
        if ent_k:
            rel = f"{base}/{ENT_DATEI}"
            path = vault / rel
            old = read_text(path) if path.exists() else None
            frueher_ent = buch.conn.execute(
                "SELECT * FROM lauf_pakete WHERE projekt=? AND status='uebernommen' AND ziel LIKE ? "
                "ORDER BY created, paket_id", (projekt, ENT_DATEI + "%")).fetchall()
            eintraege = [(r, _herkunft(r), _uebernahme_datum(r, datum)) for r in frueher_ent] + \
                [(k.row, k.herkunft, datum) for k in ent_k]
            tabelle, why = alte_tabelle(old)
            new = None
            if tabelle is not None:
                abgleich = abgleich_block(tabelle.zeilen, eintraege, {k.row["paket_id"] for k in ent_k})
                _buche_abgleich(buch, abgleich, rel, datum, lauf_id, ergebnis)
                block = "\n".join(tabelle.vor + abgleich.zeilen + tabelle.nach)
                new, why = entscheidungen_mit_uebernahme(old, projekt, block)
            elif why is None:
                new, why = entscheidungen_mit_uebernahme(old, projekt, entscheidungen_block(eintraege))
            if new is None:
                ergebnis.verweigert.append((rel, why))
                ok_ent = False
            else:
                ok_ent = writer.write(path, new, expect=old)
                if not ok_ent:
                    ergebnis.verweigert.append((rel, "schreibtor"))
                else:
                    ergebnis.zaehle(rel, "entscheidungen", len(ent_k))
        kern_ids: set[str] = set()
        kern_offen: set[str] = set()      # their KERN line could not be written: stays open
        entscheidungen = [k for k in ent_k if k.row["typ"] == "entscheidung"]
        if ok_ent and entscheidungen:
            rel = f"{base}/KERN.md"
            path = vault / rel
            wichtig = [k.row for k in sorted(entscheidungen, key=lambda k: (
                k.herkunft != "cloud-einzeln", -(k.score or 0.0), k.row["paket_id"]))]
            if path.is_file():
                old = read_text(path)
                new, added = kern_mit_gilt(old, wichtig, datum, kern_max=kern_max, top=kern_top,
                                           vermerk=freigabe or "geprüft")
                if not added:
                    ergebnis.kern_voll.append(rel)
                elif writer.write(path, new, expect=old):
                    ergebnis.zaehle(rel, "gilt", len(added))
                    kern_ids = {r["paket_id"] for r in added}
                else:
                    ergebnis.verweigert.append((rel, "schreibtor"))
                    kern_offen = {r["paket_id"] for r in added}
            else:
                ergebnis.kern_voll.append(rel)
                kern_offen = {r["paket_id"] for r in wichtig[:kern_top]}
        for k in ks:
            if k.row["paket_id"] in kern_offen:
                ergebnis.skip("kern-verweigert")
                continue
            fallen_ziel = _ziel_fallen(k.row)
            if (fallen_ziel and not ok_fallen) or (not fallen_ziel and not ok_ent):
                ergebnis.skip("ziel-verweigert")
                continue
            ziel = "FALLEN.yaml#uebernommen" if fallen_ziel else \
                ENT_DATEI + ("+KERN" if k.row["paket_id"] in kern_ids else "")
            try:
                pruefung = json.loads(k.row["pruefung"] or "{}") or {}
            except ValueError:
                pruefung = {}
            pruefung["uebernahme"] = {"herkunft": k.herkunft, "datum": datum, "lauf_id": lauf_id}
            buch.paket_update(k.row["paket_id"], status=b.UEBERNOMMEN, ziel=ziel,
                              pruefung=json.dumps(pruefung, ensure_ascii=False))
            ergebnis.uebernommen += 1
    # proposal blocks without the packages taken over (FALLEN section, brain-vorschlaege.md)
    if not writer.dry_run:
        schreib = schreiben_mod.schreiben(buch, writer, lauf_id=lauf_id)
        ergebnis.verweigert += schreib.verweigert
    buch.commit()
    ergebnis.geschrieben = list(writer.planned if writer.dry_run else writer.written)
    return ergebnis


def _buche_abgleich(buch: Buch, abgleich: BlockAbgleich, rel: str, datum: str, lauf_id: str,
                    ergebnis: UebernahmeErgebnis) -> None:
    """Hand corrections into the book (``pruefung.korrektur``) and the report."""
    for row, zeile, felder in abgleich.korrekturen:
        pruefung = _pruefung(row)
        pruefung["korrektur"] = {"zeile": zeile, "felder": felder, "datei": rel,
                                 "erkannt": datum, "lauf_id": lauf_id}
        buch.paket_update(row["paket_id"], pruefung=json.dumps(pruefung, ensure_ascii=False))
        ergebnis.handkorrekturen.append({"datei": rel, "paket_id": row["paket_id"],
                                         "felder": sorted(felder)})
    for row in abgleich.aufgehoben:
        pruefung = _pruefung(row)
        pruefung["korrektur_aufgehoben"] = {**pruefung.pop("korrektur"), "aufgehoben": datum}
        buch.paket_update(row["paket_id"], pruefung=json.dumps(pruefung, ensure_ascii=False))
        ergebnis.handkorrekturen.append({"datei": rel, "paket_id": row["paket_id"],
                                         "felder": [], "aufgehoben": True})
    for zeile in abgleich.unzugeordnet:
        ergebnis.unzugeordnet.append({"datei": rel, "zeile": zeile})
    for row, woher in abgleich.wiederhergestellt:
        ergebnis.wiederhergestellt.append({"datei": rel, "paket_id": row["paket_id"], "aus": woher})


def _buche_fallen_abgleich(buch: Buch, abgleich: FallenAbgleich, rel: str, datum: str,
                          lauf_id: str, ergebnis: UebernahmeErgebnis) -> None:
    for row, raw, fields in abgleich.korrekturen:
        pruefung = _pruefung(row)
        pruefung["korrektur"] = {"yaml": raw, "felder": fields, "datei": rel,
                                 "erkannt": datum, "lauf_id": lauf_id}
        buch.paket_update(row["paket_id"], pruefung=json.dumps(pruefung, ensure_ascii=False))
        ergebnis.handkorrekturen.append({"datei": rel, "paket_id": row["paket_id"],
                                         "felder": sorted(fields)})
    for row in abgleich.aufgehoben:
        pruefung = _pruefung(row)
        pruefung["korrektur_aufgehoben"] = {**pruefung.pop("korrektur"), "aufgehoben": datum}
        buch.paket_update(row["paket_id"], pruefung=json.dumps(pruefung, ensure_ascii=False))
        ergebnis.handkorrekturen.append({"datei": rel, "paket_id": row["paket_id"],
                                         "felder": [], "aufgehoben": True})
    for ident in abgleich.unzugeordnet:
        ergebnis.unzugeordnet.append({"datei": rel, "id": ident})
    for row, woher in abgleich.wiederhergestellt:
        ergebnis.wiederhergestellt.append({"datei": rel, "paket_id": row["paket_id"], "aus": woher})


def _pruefung(row) -> dict:
    try:
        return json.loads(row["pruefung"] or "{}") or {}
    except ValueError:
        return {}


def _herkunft(row) -> str:
    try:
        return ((json.loads(row["pruefung"] or "{}") or {}).get("uebernahme") or {}).get("herkunft", "?")
    except ValueError:
        return "?"


def _uebernahme_datum(row, fallback: str) -> str:
    try:
        return ((json.loads(row["pruefung"] or "{}") or {}).get("uebernahme") or {}).get("datum", fallback)
    except ValueError:
        return fallback

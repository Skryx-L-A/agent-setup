def lies_liste(path: Path) -> list[str]:
    """Package ids (first column; a header line ``paket_id``/``zelle`` is skipped)."""
    if not Path(path).is_file():
        return []
    ids = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        cols = [c.strip() for c in line.split("\t")]
        for col in cols[:2]:            # richtig.tsv: zelle<TAB>paket_id
            if re.fullmatch(r"[0-9a-f]{10,16}", col):
                ids.append(col)
                break
    return ids


def belegte_zellen(path: Path | None) -> list[tuple[str, str]]:
    """Cells the control sample proves (bounds enforced here)."""
    if path is None or not Path(path).is_file():
        return []
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    out = []
    for z in data.get("zellen", []):
        n, k = int(z.get("n", 0)), int(z.get("richtig", 0))
        if n and k / n >= ZELLE_PRAEZISION and wilson_unten(k, n) >= ZELLE_UNTERGRENZE:
            projekt, typ = z["zelle"].split("/", 1)
            out.append((projekt, typ))
    return out


def wilson_unten(k: int, n: int, z: float = 1.959964) -> float:
    if n == 0:
        return 0.0
    p = k / n
    d = 1 + z * z / n
    return max(0.0, ((p + z * z / (2 * n)) - z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))) / d)


def _score(row) -> float | None:
    try:
        return (json.loads(row["pruefung"] or "{}") or {}).get("score")
    except ValueError:
        return None


def kandidaten(buch: Buch, vault: Path, listen: Iterable[Path], zellen: list[tuple[str, str]],
               ergebnis: UebernahmeErgebnis) -> list[Kandidat]:
    out: list[Kandidat] = []
    seen: set[str] = set()
    projekte = {p.name for p in (vault / "20-projects").iterdir() if p.is_dir()} \
        if (vault / "20-projects").is_dir() else set()

    def passt(row) -> str | None:
        if row is None:
            return "unbekannt"
        if row["status"] not in OFFEN:
            return f"status-{row['status']}"
        if row["typ"] not in b.PRUEF_TYPEN:
            return "typ"
        if not row["projekt"] or row["projekt"] not in projekte:
            return "projekt-fehlt"
        return None

    for liste in listen:
        for pid in lies_liste(Path(liste)):
            row = buch.conn.execute("SELECT * FROM lauf_pakete WHERE paket_id LIKE ?",
                                    (pid + "%",)).fetchone()
            if row is not None and row["paket_id"] in seen:
                continue
            grund = passt(row)
            if grund:
                ergebnis.skip(grund)
                continue
            seen.add(row["paket_id"])
            out.append(Kandidat(row, "cloud-einzeln", _score(row)))
    for projekt, typ in zellen:
        ergebnis.zellen.append(f"{projekt}/{typ}")
        rows = buch.conn.execute(
            "SELECT * FROM lauf_pakete WHERE projekt=? AND typ=? AND status='vorgeschlagen' "
            "AND pruefung IS NOT NULL ORDER BY created, paket_id", (projekt, typ)).fetchall()
        for row in rows:
            if row["paket_id"] in seen or passt(row):
                continue
            seen.add(row["paket_id"])
            out.append(Kandidat(row, f"zelle:{projekt}/{typ}", _score(row)))
    return out


def kandidaten_ids(buch: Buch, vault: Path, ids: Iterable[str], freigabe: str,
                   ergebnis: UebernahmeErgebnis) -> list[Kandidat]:
    """Exactly the packages an orchestrator or the human approved (id or an
    unambiguous prefix of at least 10 characters).  Any open package of a
    known project qualifies; its selection basis becomes the approval."""
    projekte = {p.name for p in (vault / "20-projects").iterdir() if p.is_dir()} \
        if (vault / "20-projects").is_dir() else set()
    out: list[Kandidat] = []
    seen: set[str] = set()
    for pid in ids:
        pid = str(pid).strip().removeprefix("brain-")
        if not re.fullmatch(r"[0-9a-f]{10,64}", pid):
            ergebnis.skip("id-ungueltig")
            continue
        rows = buch.conn.execute("SELECT * FROM lauf_pakete WHERE paket_id LIKE ?",
                                 (pid + "%",)).fetchall()
        if len(rows) != 1:
            ergebnis.skip("unbekannt" if not rows else "id-mehrdeutig")
            continue
        row = rows[0]
        if row["paket_id"] in seen:
            continue
        if row["status"] not in OFFEN:
            ergebnis.skip(f"status-{row['status']}")
            continue
        if row["typ"] not in b.PRUEF_TYPEN:
            ergebnis.skip("typ")
            continue
        if not row["projekt"] or row["projekt"] not in projekte:
            ergebnis.skip("projekt-fehlt")
            continue
        seen.add(row["paket_id"])
        out.append(Kandidat(row, freigabe, _score(row)))
    return out


def herkunft_der_einheit(buch: Buch, row) -> dict:
    """Where a package's statement comes from: source class and path of its unit."""
    e = buch.conn.execute(
        "SELECT source_class, path FROM lauf_einheiten WHERE quell_id=? AND segment_index=? "
        "AND content_hash=?", (row["quell_id"], row["segment_index"], row["content_hash"])).fetchone()
    return {"klasse": e["source_class"] if e else "?", "pfad": e["path"] if e else "?",
            "einheit": f"{row['quell_id']}#{row['segment_index']}"}


def vorschlag(buch: Buch, k: Kandidat) -> dict:
    r = k.row
    return {"id": r["paket_id"][:10], "projekt": r["projekt"], "typ": r["typ"],
            "ziel": "FALLEN.yaml" if _ziel_fallen(r) else ENT_DATEI,
            "aussage": " ".join(str(r["aussage"]).split()),
            "gegenmittel": " ".join(str(r["gegenmittel"] or "").split()),
            "auswahl": k.herkunft, "herkunft": herkunft_der_einheit(buch, r)}


def _norm(text: str | None) -> str:
    return " ".join(re.sub(r"[^\w\s]", " ", str(text or "").casefold()).split())


def zusammenfuehren(kand: list[Kandidat], *, einbetten=None, gleich_cos: float = 0.62,
                    vorhanden: dict[str, set[str]] | None = None
                    ) -> tuple[list[Kandidat], list[tuple[Kandidat, str]]]:
    """(kept, [(duplicate, id of the kept one or 'vorhanden')]) per project.
    Order: cloud-checked first, then by score (high first)."""
    vorhanden = vorhanden or {}
    ordnung = sorted(kand, key=lambda k: (k.herkunft != "cloud-einzeln", -(k.score or 0.0),
                                          k.row["paket_id"]))
    vektoren: dict[str, list[float]] = {}
    if einbetten is not None and ordnung:
        texte = [k.row["aussage"] for k in ordnung]
        for k, v in zip(ordnung, einbetten(texte)):
            n = math.sqrt(sum(x * x for x in v)) or 1.0
            vektoren[k.row["paket_id"]] = [x / n for x in v]
    behalten: list[Kandidat] = []
    duplikate: list[tuple[Kandidat, str]] = []
    for k in ordnung:
        projekt = k.row["projekt"]
        norm = _norm(k.row["aussage"])
        if norm in vorhanden.get(projekt, set()):
            duplikate.append((k, "vorhanden"))
            continue
        mit = None
        for other in behalten:
            if other.row["projekt"] != projekt:
                continue
            if _norm(other.row["aussage"]) == norm:
                mit = other
                break
            va, vb = vektoren.get(k.row["paket_id"]), vektoren.get(other.row["paket_id"])
            if va is not None and vb is not None and sum(x * y for x, y in zip(va, vb)) >= gleich_cos:
                mit = other
                break
        if mit is not None:
            duplikate.append((k, mit.row["paket_id"]))
        else:
            behalten.append(k)
    return behalten, duplikate



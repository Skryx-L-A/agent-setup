"""`brain run uebernehmen`: take checked proposals over into FALLEN.yaml, the decision note and KERN (p3).

Since 10.10.2026 (der Nutzer, channel inventory measure 2) nothing is taken over
without an explicit OK: called without ``ids`` this module only lists the ready
proposals (``vorschlaege``, with selection basis and source unit); with ``ids``
it takes over exactly those packages and records the approval (``freigabe``) in
the book, the FALLEN comment, the decision table and the KERN line.  Who may
give the OK (an orchestrator or the human, measured) is enforced at the entry
point, ``lauf.uebernehmen`` with ``freigabe.pruefe``.

BRAIN5-PLAN Nr. 30: a cell (project x type) whose sample is at least 90 %
right goes into KERN/FALLEN, the rest stays a proposal.  The ready list holds
exactly two kinds of packages:

a) packages a cloud judge checked one by one and found right (``--liste``,
   TSV/text with the package id in the first column; default: the 90 of
   ``eval/vorschlaege-stichprobe/richtig.tsv`` and the right ones of the p3
   control sample ``eval/vorschlaege-qualitaet/kontrolle-richtig.tsv``);
b) every kept package (checked by ``pruefen`` and not rejected) of a cell
   that the control sample proves: precision >= 0.9 and Wilson lower bound
   >= 0.8 (``--zellen``, JSON written by ``eval/vorschlaege-qualitaet``;
   the bounds are enforced here, not trusted from the file).

Before anything is written, near duplicates inside the set are merged
(normalised text, and embeddings at the ``gleich_cos`` threshold when the
embedding engine answers): the first of a group is kept (cloud-checked
before cell members, then by decider score), the others become
``duplikat``.  A package whose statement already stands in the project's
FALLEN.yaml or KERN.md is ``duplikat`` too.

Targets per project ``p``:

- ``fehler``/``lehre`` with a counter-measure -> ``20-projects/p/FALLEN.yaml``,
  new entries ``status: gilt`` in the own section ``# brain:uebernommen:start/end``
  (before the proposal section); checked with PyYAML and the tripwire's
  loader. Existing entries and their file status are kept.
- ``entscheidung`` (and a ``fehler``/``lehre`` without counter-measure) ->
  table in the marker block ``<!-- brain:uebernommen:start/end -->`` of
  ``20-projects/p/ENTSCHEIDUNGEN-UND-FALLEN.md`` (created if missing).
- at most ``KERN_TOP`` decisions per project additionally as a line under
  ``## Gilt`` in ``KERN.md``, only while its body (the text after the
  frontmatter, as `brain doctor` and the session start count it) stays within
  ``KERN_MAX`` characters.  A decision whose KERN line cannot be written (the
  write gate refuses KERN.md: ``verweigert``; KERN.md is missing: ``kern_voll``)
  is not marked taken over, so a later run retries it.

The marker block is regenerated from the book on every take-over, but hand
corrections survive it (b7, 2026-09-29): the table rows of the existing block
are matched to their packages (source cell, then statement); a row that
differs from what the book would write is kept as it stands in the file, its
fields are written back into the book (``pruefung.korrektur``) and reported
(``handkorrekturen``).  A row that matches no package stays too
(``unzugeordnet``), a taken-over package missing from the file comes back
(its corrected row when the book has one; ``wiederhergestellt``).  No row is
ever dropped silently.

The same rule applies to the YAML marker block: existing entries keep their
raw text and status, changed fields are recorded in ``pruefung.korrektur``,
unmatched entries stay, and missing package entries return from the book.

Book status ``uebernommen`` (``ziel`` names the file); afterwards the
proposal blocks are regenerated by ``schreiben`` without them.  One lock with
`brain run`, one commit, never a push.  ``--dry-run`` writes nothing (book in
memory, writer only plans) and reports the amounts per file.
"""

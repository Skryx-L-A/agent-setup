def _ziel_fallen(row) -> bool:
    return row["typ"] in schreiben_mod.FALLEN_TYPEN and bool((row["gegenmittel"] or "").strip())


TRIGGER_KEYS = ("pfad", "befehl", "diff")


def _yaml_roh(text) -> str:
    """Double-quoted YAML scalar that keeps the text byte for byte (a regex:
    no whitespace folding), readable by PyYAML and the tripwire's loader."""
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def trigger_zeilen(anker, ausloeser) -> list[str]:
    """YAML lines for an entry's ``anker`` and ``ausloeser`` (FALLEN-SCHEMA)."""
    out = []
    if anker:
        out.append(f"    anker: {_yaml_roh(anker)}")
    if ausloeser:
        out.append("    ausloeser:")
        for t in ausloeser:
            keys = [k for k in TRIGGER_KEYS if t.get(k)]
            for i, k in enumerate(keys):
                out.append(("      - " if i == 0 else "        ") + f"{k}: {_yaml_roh(t[k])}")
    return out


def _fallen_eintrag(row, herkunft: str, datum: str, extra: dict | None = None) -> str:
    y = schreiben_mod._yaml_str
    extra = extra or {}
    return "\n".join([
        f"  - id: brain-{row['paket_id'][:10]}",
        f"    falle: {y(row['aussage'])}",
        f"    gegenmittel: {y(row['gegenmittel'])}",
        f"    quelle: {y(schreiben_mod.quelle(row))}",
        f"    seit: {y(row['datum'] or datum)}",
        "    status: gilt",
        "    abgeloest_durch: null",
        "    schaden: 1",
    ] + trigger_zeilen(extra.get("anker"), extra.get("ausloeser")) + [
        f"    # typ {row['typ']}, uebernommen {datum} mit `brain run uebernehmen` ({herkunft}); "
        "schaden ungeschaetzt",
    ])


def fallen_abschnitt(eintraege: list[tuple[Any, str, str]], extra: dict[str, dict] | None = None) -> str:
    """The own section; ``extra`` (id ``brain-…`` -> {anker, ausloeser}) carries
    fields added after the take-over (d1: triggers), so regenerating the section
    from the book keeps them."""
    extra = extra or {}
    body = [UEB_YAML_START + " -- von `brain run uebernehmen` uebernommen (geprueft)"]
    body += [_fallen_eintrag(row, herkunft, datum, extra.get(f"brain-{row['paket_id'][:10]}"))
             for row, herkunft, datum in eintraege]
    body.append(UEB_YAML_END)
    return "\n".join(body) + "\n"


@dataclass
class FallenAbgleich:
    abschnitt: str
    korrekturen: list[tuple[Any, str, dict]] = field(default_factory=list)
    aufgehoben: list[Any] = field(default_factory=list)
    unzugeordnet: list[str] = field(default_factory=list)
    wiederhergestellt: list[tuple[Any, str]] = field(default_factory=list)
    status: dict[str, str] = field(default_factory=dict)


def _fallen_korrektur(row) -> dict | None:
    k = _pruefung(row).get("korrektur")
    return k if isinstance(k, dict) and isinstance(k.get("yaml"), str) else None


def _fallen_bloecke(text: str) -> tuple[str, list[tuple[str, str]], str] | None:
    """Raw YAML entries in the owned marker block, keeping comments and spacing."""
    lines = text.splitlines(keepends=True)
    starts = [i for i, line in enumerate(lines) if line.rstrip("\n").startswith(UEB_YAML_START)]
    ends = [i for i, line in enumerate(lines) if line.rstrip("\n") == UEB_YAML_END]
    if len(starts) != 1 or len(ends) != 1 or starts[0] >= ends[0]:
        return None
    body = lines[starts[0] + 1:ends[0]]
    positions = [i for i, line in enumerate(body) if line.startswith("  - ")]
    prefix = "".join(lines[starts[0]:starts[0] + 1] + body[:positions[0] if positions else len(body)])
    if not positions:
        return prefix, [], lines[ends[0]]
    entries = []
    for index, pos in enumerate(positions):
        raw = "".join(body[pos:positions[index + 1] if index + 1 < len(positions) else len(body)])
        match = re.match(r"  - id: ([^\s#]+)\s*(?:#.*)?\n", raw)
        if match is None:
            return None
        entries.append((match.group(1), raw))
    if len({ident for ident, _ in entries}) != len(entries):
        return None
    return prefix, entries, lines[ends[0]]


def abgleich_fallen(old: str | None, eintraege: list[tuple[Any, str, str]],
                    neu_ids: set[str]) -> tuple[FallenAbgleich | None, str | None]:
    """The file owns existing entries; the book restores entries removed by hand."""
    generated = {f"brain-{row['paket_id'][:10]}": (row, _fallen_eintrag(row, h, d) + "\n")
                 for row, h, d in eintraege}
    if old is None or (UEB_YAML_START not in old and UEB_YAML_END not in old):
        result = FallenAbgleich(fallen_abschnitt(eintraege))
        result.status = {ident: "gilt" for ident in generated}
        return result, None
    parsed = _fallen_bloecke(old)
    if parsed is None:
        return None, "abschnitt-unlesbar"
    prefix, entries, end = parsed
    out = FallenAbgleich("")
    parts = [prefix]
    seen = set()
    import yaml
    for ident, raw in entries:
        parts.append(raw)
        if ident not in generated:
            out.unzugeordnet.append(ident)
            continue
        seen.add(ident)
        row, standard = generated[ident]
        try:
            actual = yaml.safe_load("fallen:\n" + raw)["fallen"][0]
            expected = yaml.safe_load("fallen:\n" + standard)["fallen"][0]
        except (yaml.YAMLError, AttributeError, KeyError, IndexError, TypeError):
            return None, "abschnitt-unlesbar"
        out.status[ident] = actual.get("status")
        previous = _fallen_korrektur(row)
        if raw != standard:
            fields = {key: actual.get(key) for key in actual.keys() | expected.keys()
                      if actual.get(key) != expected.get(key)}
            if previous is None or previous.get("yaml") != raw:
                out.korrekturen.append((row, raw, fields))
        elif previous is not None:
            out.aufgehoben.append(row)
    for ident, (row, standard) in generated.items():
        if ident in seen:
            continue
        previous = _fallen_korrektur(row)
        restored = previous["yaml"] if previous else standard
        parts.append(restored)
        try:
            out.status[ident] = yaml.safe_load("fallen:\n" + restored)["fallen"][0].get("status")
        except (yaml.YAMLError, AttributeError, KeyError, IndexError, TypeError):
            return None, "buchkorrektur-unlesbar"
        if row["paket_id"] not in neu_ids:
            out.wiederhergestellt.append((row, "buch" if previous else "erzeugt"))
    parts.append(end)
    out.abschnitt = "".join(parts)
    return out, None


def _ohne_vorschlaege(text: str, ids: set[str]) -> str:
    """Drop the proposal entries ``brain-<id>`` of ``ids`` from the proposal
    section of ``schreiben`` (they are taken over, not proposed any more)."""
    lines = text.splitlines(keepends=True)
    out, inside, skip = [], False, False
    for line in lines:
        bare = line.rstrip("\n")
        if bare.startswith(schreiben_mod.YAML_START):
            inside, skip = True, False
        elif bare == schreiben_mod.YAML_END:
            inside, skip = False, False
        elif inside and line.startswith("  - "):
            m = re.match(r"  - id: brain-([0-9a-f]+)", bare)
            skip = bool(m and m.group(1) in ids)
        if not skip:
            out.append(line)
    return "".join(out)


def fallen_mit_uebernahme(existing: str | None, projekt: str, section: str,
                          ids: set[str] = frozenset()) -> tuple[str | None, str]:
    """File text with the own section, or (None, reason)."""
    if existing is not None and ids:
        existing = _ohne_vorschlaege(existing, ids)
    if existing is None:
        head = (f"# Fallenbuch {projekt}. Schema: _meta/tools/hooks/FALLEN-SCHEMA.md.\n"
                "# Angelegt von `brain run uebernehmen`.\n"
                f"version: 1\nprojekt: {projekt}\nfallen:\n")
        return head + section, "neu"
    lines = existing.splitlines(keepends=True)
    top_keys = [i for i, line in enumerate(lines)
                if line[:1].isalpha() and ":" in line and not line.startswith("#")]
    if not top_keys or not lines[top_keys[-1]].startswith("fallen:"):
        return None, "fallen-nicht-letzter-schluessel"
    s = [i for i, line in enumerate(lines) if line.rstrip("\n").startswith(UEB_YAML_START)]
    e = [i for i, line in enumerate(lines) if line.rstrip("\n") == UEB_YAML_END]
    if len(s) > 1 or len(e) > 1 or bool(s) != bool(e) or (s and e[0] < s[0]):
        return None, "abschnitt-kaputt"
    if s:
        return "".join(lines[:s[0]]) + section + "".join(lines[e[0] + 1:]), "ok"
    vorschlag = next((i for i, line in enumerate(lines)
                      if line.rstrip("\n").startswith(schreiben_mod.YAML_START)), None)
    if vorschlag is not None:
        return "".join(lines[:vorschlag]) + section + "\n" + "".join(lines[vorschlag:]), "ok"
    head = existing if existing.endswith("\n") else existing + "\n"
    return head + section, "ok"


def pruefe_fallen(old: str | None, new: str, loader, neue_ids: set[str],
                  status: dict[str, str] | None = None) -> str | None:
    """None when ``new`` parses (PyYAML and the tripwire loader), keeps every
    other entry unchanged and has the taken-over ids with the file status."""
    problem = schreiben_mod._pyyaml_fehler(new)
    if problem:
        return f"yaml-unlesbar: {problem}"
    try:
        import yaml
        parsed = yaml.safe_load(new) or {}
    except ImportError:             # pragma: no cover - PyYAML is a dependency
        parsed = None
    lader = [loader] if loader is not None else []
    for load in lader + ([lambda t: yaml.safe_load(t)] if parsed is not None else []):
        try:
            before = ((load(old) or {}).get("fallen") or []) if old is not None else []
            after = (load(new) or {}).get("fallen") or []
        except Exception as exc:   # noqa: BLE001 - any parser complaint refuses the write
            return f"yaml-unlesbar: {exc}"

        def eigen(entry) -> bool:
            return isinstance(entry, dict) and str(entry.get("id", ""))[len("brain-"):] in neue_ids \
                and str(entry.get("id", "")).startswith("brain-")
        if [x for x in after if not eigen(x)] != [x for x in before if not eigen(x)]:
            return "bestehende-eintraege-veraendert"
        got = {str(x["id"])[len("brain-"):]: x for x in after if eigen(x)}
        old_by_id = {str(x.get("id")): x for x in before if isinstance(x, dict)}
        if set(got) != neue_ids or any(
                x.get("status") != (status or {}).get(
                    str(x.get("id")), old_by_id.get(str(x.get("id")), {}).get("status", "gilt"))
                for x in got.values()):
            return "uebernahme-unvollstaendig"
    return None


def _cell(text: str | None) -> str:
    return schreiben_mod._cell(text)


TABELLE_KOPF = "| Datum | Typ | Aussage | Gegenmittel | Quelle (Satz-IDs) | übernommen | Status |"
SPALTEN = ("datum", "typ", "aussage", "gegenmittel", "quelle", "uebernommen", "status")


def entscheidungen_zeile(row, herkunft: str, datum: str) -> str:
    return (f"| {_cell(row['datum'])} | {row['typ']} | {_cell(row['aussage'])} | "
            f"{_cell(row['gegenmittel'])} | {_cell(schreiben_mod.quelle(row))} | "
            f"{datum} ({herkunft}) | gilt |")


def entscheidungen_block(eintraege: list[tuple[Any, str, str]]) -> str:
    out = [UEB_MD_START, "## Übernommen aus der Pipeline (geprüft)", "",
           "Von `brain run uebernehmen` übertragen: einzeln cloud-geprüfte Vorschläge und Vorschläge "
           "aus Zellen, deren Kontrollstichprobe mindestens 90 % richtig war "
           "(`_meta/tools/eval/vorschlaege-qualitaet/`). Quelle = Einheit und Satz-IDs.", "",
           TABELLE_KOPF, "|---|---|---|---|---|---|---|"]
    out += [entscheidungen_zeile(row, herkunft, datum) for row, herkunft, datum in eintraege]
    out.append(UEB_MD_END)
    return "\n".join(out)


def zellen_der_zeile(line: str) -> list[str] | None:
    """Cells of a table row (escaped ``\\|`` stays inside a cell, text kept
    as written), or None when the line is no table row."""
    bare = line.strip()
    if not bare.startswith("|") or not bare.endswith("|") or len(bare) < 2:
        return None
    return [c.strip() for c in re.split(r"(?<!\\)\|", bare[1:-1])]


def _quelle_passt(zelle: str, erzeugt: str) -> bool:
    """The source cell starts with the generated source; a hand addition may
    follow after a space, ``;`` or ``(`` (``S22 (historisch)``, ``S9; R: …``)."""
    if not erzeugt:
        return False
    return zelle == erzeugt or (zelle.startswith(erzeugt) and zelle[len(erzeugt)] in " ;(")


@dataclass
class BlockAbgleich:
    zeilen: list[str]                                   # table body, in order
    korrekturen: list[tuple[Any, str, dict]] = field(default_factory=list)   # (row, zeile, felder)
    aufgehoben: list[Any] = field(default_factory=list)  # book correction, file row back to generated
    unzugeordnet: list[str] = field(default_factory=list)
    wiederhergestellt: list[tuple[Any, str]] = field(default_factory=list)   # (row, "buch"|"erzeugt")


def _korrektur(row) -> dict | None:
    try:
        k = (json.loads(row["pruefung"] or "{}") or {}).get("korrektur")
    except (ValueError, IndexError, KeyError):
        return None
    return k if isinstance(k, dict) and k.get("zeile") else None


def abgleich_block(alt_zeilen: list[str], eintraege: list[tuple[Any, str, str]],
                   neu_ids: set[str] = frozenset()) -> BlockAbgleich:
    """Merge the table rows of the existing block with the packages.

    Every file row is kept in its place: a row assigned to a package keeps its
    file text (a difference to the generated row is a hand correction); a row
    no package claims stays as it is.  Packages without a row follow in book
    order.  Assignment passes: identical row, identical source cell, source
    prefix (hand additions behind it; unique, else identical statement), then
    identical statement alone."""
    erzeugt = {row["paket_id"]: entscheidungen_zeile(row, h, d) for row, h, d in eintraege}
    rows = {row["paket_id"]: row for row, _h, _d in eintraege}
    quelle = {pid: _cell(schreiben_mod.quelle(r)) for pid, r in rows.items()}
    aussage = {pid: _norm(r["aussage"]) for pid, r in rows.items()}
    zellen = [zellen_der_zeile(z) for z in alt_zeilen]
    zu: dict[int, str] = {}
    frei = [pid for pid in rows]

    def vergib(i: int, pid: str) -> None:
        zu[i] = pid
        frei.remove(pid)

    for i, z in enumerate(alt_zeilen):                       # 1: identical row
        pid = next((p for p in frei if erzeugt[p] == z.strip()), None)
        if pid:
            vergib(i, pid)
    for i, c in enumerate(zellen):                           # 2: identical source cell
        if i in zu or not c or len(c) < 5:
            continue
        treffer = [p for p in frei if quelle[p] == c[4]]
        if len(treffer) > 1:
            treffer = [p for p in treffer if aussage[p] == _norm(c[2])] or treffer[:0]
        if len(treffer) == 1:
            vergib(i, treffer[0])
    for i, c in enumerate(zellen):                           # 3: source prefix
        if i in zu or not c or len(c) < 5:
            continue
        treffer = [p for p in frei if _quelle_passt(c[4], quelle[p])]
        if len(treffer) > 1:
            laengste = max(len(quelle[p]) for p in treffer)
            treffer = [p for p in treffer if len(quelle[p]) == laengste]
        if len(treffer) > 1:
            treffer = [p for p in treffer if aussage[p] == _norm(c[2])]
        if len(treffer) == 1:
            vergib(i, treffer[0])
    for i, c in enumerate(zellen):                           # 4: identical statement
        if i in zu or not c or len(c) < 3:
            continue
        treffer = [p for p in frei if aussage[p] == _norm(c[2])]
        if len(treffer) == 1:
            vergib(i, treffer[0])

    out = BlockAbgleich(zeilen=[])
    for i, z in enumerate(alt_zeilen):
        z = z.strip()
        out.zeilen.append(z)
        pid = zu.get(i)
        if pid is None:
            out.unzugeordnet.append(z)
            continue
        alt = _korrektur(rows[pid])
        if z != erzeugt[pid]:
            c, e = zellen[i] or [], zellen_der_zeile(erzeugt[pid]) or []
            felder = {name: c[j] for j, name in enumerate(SPALTEN)
                      if j < len(c) and (j >= len(e) or c[j] != e[j])}
            if alt is None or alt.get("zeile") != z:
                out.korrekturen.append((rows[pid], z, felder))
        elif alt is not None:
            out.aufgehoben.append(rows[pid])
    for pid in frei:
        alt = _korrektur(rows[pid])
        out.zeilen.append(alt["zeile"] if alt else erzeugt[pid])
        if pid not in neu_ids:
            out.wiederhergestellt.append((rows[pid], "buch" if alt else "erzeugt"))
    return out


@dataclass
class AlteTabelle:
    vor: list[str]          # block lines up to and including the separator row
    zeilen: list[str]       # table body
    nach: list[str]         # the rest of the block including the end marker


def alte_tabelle(existing: str | None) -> tuple[AlteTabelle | None, str | None]:
    """The table of the existing marker block, ``(None, None)`` without a
    block, ``(None, reason)`` when its table is unreadable (then nothing is
    written: a changed header must not lose rows).  Text before and after the
    table (a hand note) is kept as it stands."""
    if existing is None or blocks.block_state(existing, UEB_MD_START, UEB_MD_END) != blocks.ONE:
        return None, None
    lines = (blocks.block_of(existing, UEB_MD_START, UEB_MD_END) or "").rstrip("\n").split("\n")
    kopf = [i for i, line in enumerate(lines) if line.strip() == TABELLE_KOPF]
    if len(kopf) != 1 or kopf[0] + 1 >= len(lines) or \
            not re.fullmatch(r"\|(\s*:?-+:?\s*\|)+", lines[kopf[0] + 1].strip()):
        return None, "tabelle-unlesbar"
    j = kopf[0] + 2
    ende = j
    while ende < len(lines) and lines[ende].strip().startswith("|"):
        ende += 1
    return AlteTabelle(lines[:j], [z.strip() for z in lines[j:ende]], lines[ende:]), None


def entscheidungen_mit_uebernahme(existing: str | None, projekt: str, block: str) -> tuple[str | None, str]:
    if existing is None:
        heute = dt.date.today().isoformat()
        head = ("---\n"
                f"title: {projekt} ENTSCHEIDUNGEN-UND-FALLEN\n"
                "type: decision\nclass: knowledge\n"
                f"branch: 20-projects/{projekt}\n"
                f"tags: [{projekt}, entscheidungen, fehler]\n"
                f'created: "{heute}"\nbeleg: berichtet\n---\n\n'
                f"Für künftige Sessions: geprüfte Entscheidungen und Lehren in {projekt}, übernommen "
                "aus der Pipeline `brain run`. Kurzfassung für den Sessionstart: KERN.md des Projekts.\n\n")
        return head + block + "\n", "neu"
    state = blocks.block_state(existing, UEB_MD_START, UEB_MD_END)
    if state == blocks.MALFORMED:
        return None, "markerblock-kaputt"
    if state == blocks.ONE:
        new, _ = blocks.replace_block(existing, UEB_MD_START, UEB_MD_END, block)
        return new, "ok"
    m = re.search(r"^## Relations\s*$", existing, flags=re.MULTILINE)
    if m:
        return existing[:m.start()] + block + "\n\n" + existing[m.start():], "ok"
    return existing.rstrip("\n") + "\n\n" + block + "\n", "ok"


def kern_zeile(row, datum: str, vermerk: str = "geprüft") -> str:
    return (f"- {' '.join(str(row['aussage']).split())} — {row['datum'] or datum}, "
            f"Pipeline-Paket {row['paket_id'][:10]} ({vermerk}, übernommen {datum})")


def kern_koerper(text: str) -> str:
    """KERN.md without frontmatter: the text `brain doctor` and the session start measure."""
    if text.startswith("---\n") and "\n---\n" in text[4:]:
        return text[4:].split("\n---\n", 1)[1]
    return text


def kern_mit_gilt(existing: str, rows: list, datum: str, *, kern_max: int = KERN_MAX,
                  top: int = KERN_TOP, vermerk: str = "geprüft") -> tuple[str, list]:
    """(new text, rows added) -- lines appended under ``## Gilt`` while the
    body (without frontmatter) stays within ``kern_max`` characters; an
    assertion already present is not repeated."""
    m = re.search(r"^## Gilt\s*$\n(?P<inhalt>.*?)(?=^## |\Z)", existing, flags=re.MULTILINE | re.DOTALL)
    if not m:
        return existing, []
    inhalt = m.group("inhalt")
    body = inhalt.rstrip("\n")
    added = []
    text = existing
    for row in rows[:top]:
        if _norm(row["aussage"]) in _norm(body):
            continue
        line = kern_zeile(row, datum, vermerk)
        candidate_body = body + "\n" + line
        candidate = existing[:m.start("inhalt")] + candidate_body + "\n" + \
            ("\n" if inhalt.endswith("\n\n") else "") + existing[m.end("inhalt"):]
        if len(kern_koerper(candidate)) > kern_max:
            break
        body, text = candidate_body, candidate
        added.append(row)
    return text, added


def vorhandene_aussagen(vault: Path, projekt: str, loader) -> set[str]:
    """Normalised statements already in FALLEN.yaml (``falle``) and KERN.md lines."""
    out: set[str] = set()
    base = vault / "20-projects" / projekt
    fallen = base / "FALLEN.yaml"
    if fallen.is_file() and loader is not None:
        try:
            for e in (loader(read_text(fallen)) or {}).get("fallen") or []:
                if isinstance(e, dict) and e.get("falle") and e.get("status") == "gilt":
                    out.add(_norm(e["falle"]))
        except Exception:          # noqa: BLE001 - an unreadable file adds nothing
            pass
    kern = base / "KERN.md"
    if kern.is_file():
        for line in read_text(kern).splitlines():
            if line.startswith("- "):
                out.add(_norm(line[2:].split(" — ")[0]))
    return out


